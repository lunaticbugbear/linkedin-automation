const ORDER = ['id', 'en', 'zh'];

function t(lang, key, vars = {}) {
  const l = DICT[lang] ? lang : (DICT[String(lang)] ? String(lang) : 'en');
  let s = (DICT[l] && DICT[l][key]) || (DICT.en && DICT.en[key]) || (DICT.id && DICT.id[key]) || key;
  for (const k of Object.keys(vars)) {
    s = s.split(`{${k}}`).join(String(vars[k]));
  }
  return s;
}

function normalizeLang(code) {
  const c = String(code || '').toLowerCase();
  if (c.startsWith('zh')) return 'zh';
  if (c.startsWith('en')) return 'en';
  if (c.startsWith('id')) return 'id';
  return '';
}

export { DICT, t, ORDER, normalizeLang };
